#!/usr/bin/env node
/**
 * Regenerate `supabase/functions/_shared/oddspapiFootballCatalog.ts` (OddsPapi football market ids + team names)
 * so the Circa feed never spends free-tier requests on catalogs. Costs 2 OddsPapi requests (of 250/mo).
 *
 *   node scripts/oddspapi-football-catalog.mjs            # fetch with ODDSPAPI_API_KEY from .env.local
 *   node scripts/oddspapi-football-catalog.mjs --from-tmp # reuse /tmp/op_markets.json + /tmp/op_parts.json
 */
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const outFile = path.join(root, 'supabase/functions/_shared/oddspapiFootballCatalog.ts')

function envKey() {
  if (process.env.ODDSPAPI_API_KEY) return process.env.ODDSPAPI_API_KEY
  const env = fs.readFileSync(path.join(root, '.env.local'), 'utf8')
  return env.match(/^ODDSPAPI_API_KEY=(.+)$/m)?.[1]?.trim()
}

async function get(pathname) {
  const key = envKey()
  if (!key) throw new Error('ODDSPAPI_API_KEY missing')
  const res = await fetch(`https://api.oddspapi.io/v4/${pathname}&apiKey=${key}`)
  if (!res.ok) throw new Error(`${pathname}: ${res.status}`)
  return res.json()
}

const fromTmp = process.argv.includes('--from-tmp')
const markets = fromTmp
  ? JSON.parse(fs.readFileSync('/tmp/op_markets.json', 'utf8'))
  : await get('markets?sportId=14')
if (!fromTmp) await new Promise((r) => setTimeout(r, 1200))
const participants = fromTmp
  ? JSON.parse(fs.readFileSync('/tmp/op_parts.json', 'utf8'))
  : await get('participants?sportId=14')

/** marketId → [kind, handicap, firstOutcomeId] … kind m/s/t; first outcome = team 1 (m/s) or Over (t). */
const marketMap = {}
for (const m of markets) {
  if (m.sportId !== 14 || m.period !== 'result' || m.playerProp) continue
  const kind = { moneyline: 'm', spreads: 's', totals: 't' }[m.marketType]
  if (!kind) continue
  const first = m.outcomes.find((o) => o.outcomeName === (kind === 't' ? 'Over' : '1'))
  if (first) marketMap[m.marketId] = [kind, m.handicap, first.outcomeId]
}

const header = `// Generated by scripts/oddspapi-football-catalog.mjs … do not edit by hand.
// OddsPapi sportId 14 full-game moneyline / spread / total market ids and participant names.
`
fs.writeFileSync(
  outFile,
  `${header}
/** marketId → [kind ('m' | 's' | 't'), handicap (team 1 / total), first outcomeId (team 1 or Over)] */
export const ODDSPAPI_FOOTBALL_MARKETS: Record<string, [string, number, number]> = ${JSON.stringify(marketMap)}

export const ODDSPAPI_FOOTBALL_PARTICIPANTS: Record<string, string> = ${JSON.stringify(participants)}
`,
)
console.log(`wrote ${outFile} (${Object.keys(marketMap).length} markets, ${Object.keys(participants).length} teams)`)
