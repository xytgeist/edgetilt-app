-- Weekly history of the ESPN Analytics NFL team win-rate board.
-- ESPN updates one article in place, and nfl_team_metrics holds only the latest
-- values, so without this table past boards are gone. Written by
-- scripts/sync-espn-nfl-trench-live.mjs on every new board; read by
-- scripts/syndicate-trench-recalibrate.mjs. Service role only.

create table if not exists public.nfl_trench_board_snapshots (
  season int not null,
  through_week int not null,
  team_abbr text not null,
  pass_block_win_rate numeric not null,
  pass_rush_win_rate numeric not null,
  run_block_win_rate numeric not null,
  run_stop_win_rate numeric not null,
  source text,
  source_updated_at timestamptz,
  captured_at timestamptz not null default now(),
  primary key (season, through_week, team_abbr)
);

alter table public.nfl_trench_board_snapshots enable row level security;

